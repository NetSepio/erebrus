// Package policy applies Sentinel DNS rules to generated Unbound fragments.
package policy

import (
	"encoding/json"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strings"
)

// Rule is a gateway-managed firewall rule (subset of gateway firewall_rules).
type Rule struct {
	RuleType string `json:"rule_type"`
	Target   string `json:"target"`
	Action   string `json:"action"`
	Value    string `json:"value,omitempty"`
	Enabled  bool   `json:"enabled"`
}

// Policy is the payload for POST /policy/apply and POST /rules/sync.
type Policy struct {
	OrgID     string   `json:"org_id"`
	NodeID    string   `json:"node_id"`
	Rules     []Rule   `json:"rules"`
	Upstreams []string `json:"upstreams"`
}

// Writer generates Unbound conf.d fragments under dir.
type Writer struct {
	Dir string
}

// Apply writes blocklist, allowlist, rewrites, and upstreams fragments.
func (w *Writer) Apply(p Policy) error {
	if err := Validate(p); err != nil {
		return err
	}
	if err := os.MkdirAll(w.Dir, 0o755); err != nil {
		return err
	}
	blocks, allows, rewrites, upstreams := w.render(p)
	files := map[string]string{
		"blocklist.conf": blocks,
		"allowlist.conf": allows,
		"rewrites.conf":  rewrites,
		"upstreams.conf": upstreams,
		"base.conf":      "# generated by erebrus-sentinel\n",
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(w.Dir, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Validate rejects values that cannot safely be rendered into Unbound config.
func Validate(p Policy) error {
	if len(p.Rules) > 10_000 || len(p.Upstreams) > 32 {
		return fmt.Errorf("policy exceeds rule or upstream limit")
	}
	for _, rule := range p.Rules {
		if !rule.Enabled {
			continue
		}
		target := strings.TrimPrefix(strings.TrimSpace(rule.Target), "*.")
		if !validDomain(target) {
			return fmt.Errorf("invalid policy domain %q", rule.Target)
		}
		action := strings.ToLower(strings.TrimSpace(rule.Action))
		if action == "rewrite" || action == "dns_rewrite" {
			if net.ParseIP(strings.TrimSpace(rule.Value)) == nil {
				return fmt.Errorf("invalid rewrite address for %q", rule.Target)
			}
		}
	}
	for _, upstream := range p.Upstreams {
		value := strings.TrimPrefix(strings.TrimPrefix(strings.TrimSpace(upstream), "tls://"), "https://")
		if value == "" || len(value) > 253 {
			return fmt.Errorf("invalid upstream %q", upstream)
		}
		for _, r := range value {
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') ||
				(r >= '0' && r <= '9') || strings.ContainsRune(".:-_@#", r) {
				continue
			}
			return fmt.Errorf("invalid upstream %q", upstream)
		}
	}
	return nil
}

func validDomain(value string) bool {
	value = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(value)), ".")
	if value == "" || len(value) > 253 {
		return false
	}
	for _, label := range strings.Split(value, ".") {
		if label == "" || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return false
		}
		for _, r := range label {
			if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
				continue
			}
			return false
		}
	}
	return true
}

func (w *Writer) render(p Policy) (blocks, allows, rewrites, upstreams string) {
	for _, r := range p.Rules {
		if !r.Enabled {
			continue
		}
		target := dnsZone(r.Target)
		action := strings.ToLower(strings.TrimSpace(r.Action))
		switch action {
		case "block", "domain_block", "wildcard_domain_block":
			if strings.HasPrefix(strings.TrimSpace(r.Target), "*.") {
				wild := strings.TrimPrefix(strings.TrimSpace(r.Target), "*.")
				blocks += fmt.Sprintf("local-zone: %q always_nxdomain\n", dnsZone(wild))
			} else {
				blocks += fmt.Sprintf("local-zone: %q always_nxdomain\n", target)
			}
		case "allow", "domain_allow":
			allows += fmt.Sprintf("local-zone: %q transparent\n", target)
		case "rewrite", "dns_rewrite":
			val := strings.TrimSpace(r.Value)
			if val == "" {
				val = strings.TrimSpace(r.Action)
			}
			if val == "" || val == "rewrite" || val == "dns_rewrite" {
				continue
			}
			recordType := "A"
			if ip := net.ParseIP(val); ip != nil && ip.To4() == nil {
				recordType = "AAAA"
			}
			rewrites += fmt.Sprintf("local-zone: %q static\n", target)
			rewrites += fmt.Sprintf("local-data: %q 60 IN %s %s\n", target, recordType, val)
		}
	}
	if len(p.Upstreams) > 0 {
		upstreams = "forward-zone:\n  name: \".\"\n  forward-tls-upstream: yes\n"
		for _, u := range p.Upstreams {
			addr := strings.TrimPrefix(strings.TrimPrefix(u, "tls://"), "https://")
			if strings.Contains(addr, "@") {
				upstreams += fmt.Sprintf("  forward-addr: %s\n", addr)
			} else {
				upstreams += fmt.Sprintf("  forward-addr: %s@853\n", addr)
			}
		}
	}
	return
}

func dnsZone(host string) string {
	host = strings.TrimSpace(strings.ToLower(host))
	host = strings.TrimSuffix(host, ".")
	return host + "."
}

// ParsePolicy decodes a policy JSON body.
func ParsePolicy(raw json.RawMessage) (Policy, error) {
	var p Policy
	if len(raw) == 0 {
		return p, nil
	}
	err := json.Unmarshal(raw, &p)
	return p, err
}
